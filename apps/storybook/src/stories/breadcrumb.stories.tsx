// Stories follow the upstream shadcn/ui (base-nova) Breadcrumb examples:
// https://ui.shadcn.com/docs/components/base/breadcrumb
const meta = {
  title: "Components/Breadcrumb",
  component: Breadcrumb,
  subcomponents: {
    BreadcrumbEllipsis,
    BreadcrumbItem,
    BreadcrumbLink,
    BreadcrumbList,
    BreadcrumbPage,
    BreadcrumbSeparator,
  },
  parameters: {
    docs: {
      description: {
        component:
          "Displays the path to the current resource using a hierarchy of links.",
      },
    },
  },
} satisfies Meta<typeof Breadcrumb>

export default meta
type Story = StoryObj<typeof meta>

// Stands in for a router link; upstream uses `next/link`.
function Link(props: React.ComponentProps<"a">) {
  return <a {...props} />
}

