import type { Meta, StoryObj } from "@storybook/react-vite"
import { BluetoothIcon, CircleFadingPlusIcon, Trash2Icon } from "lucide-react"
import {
  AlertDialog,
  AlertDialogAction,
  AlertDialogCancel,
  AlertDialogContent,
  AlertDialogDescription,
  AlertDialogFooter,
  AlertDialogHeader,
  AlertDialogMedia,
  AlertDialogTitle,
  AlertDialogTrigger,
} from "@amit-kap/glaze/components/alert-dialog"
import { Button } from "@amit-kap/glaze/components/button"

// Stories follow the upstream shadcn/ui (base-nova) Alert Dialog examples:
// https://ui.shadcn.com/docs/components/base/alert-dialog
// Skipped: "Basic", which only differs from the demo by one sentence.
const meta = {
  title: "Components/Alert Dialog",
  component: AlertDialog,
  subcomponents: {
    AlertDialogAction,
    AlertDialogCancel,
    AlertDialogContent,
    AlertDialogDescription,
    AlertDialogFooter,
    AlertDialogHeader,
    AlertDialogMedia,
    AlertDialogTitle,
    AlertDialogTrigger,
  },
  parameters: {
    docs: {
      description: {
        component:
          "A modal dialog that interrupts the user with important content and expects a response. Unlike Dialog, it has no close button and does not close when clicking outside.",
      },
    },
  },
  argTypes: {
    defaultOpen: { control: "boolean" },
  },
  render: (args) => (
    <AlertDialog {...args}>
      <AlertDialogTrigger render={<Button variant="outline" />}>
        Show Dialog
      </AlertDialogTrigger>
      <AlertDialogContent>
        <AlertDialogHeader>
          <AlertDialogTitle>Are you absolutely sure?</AlertDialogTitle>
          <AlertDialogDescription>
            This action cannot be undone. This will permanently delete your
            account from our servers.
          </AlertDialogDescription>
        </AlertDialogHeader>
        <AlertDialogFooter>
          <AlertDialogCancel>Cancel</AlertDialogCancel>
          <AlertDialogAction>Continue</AlertDialogAction>
        </AlertDialogFooter>
      </AlertDialogContent>
    </AlertDialog>
  ),
} satisfies Meta<typeof AlertDialog>

export default meta
type Story = StoryObj<typeof meta>

// --- Basic ----------------------------------------------------------------

export const Default: Story = {}

// --- States ---------------------------------------------------------------

export const Open: Story = {
  args: { defaultOpen: true },
}

// --- Sizes ----------------------------------------------------------------

