import type { GlazeConfig } from "@amit-kap/glaze/lib/config"

// Turns a Glaze config into a theme stylesheet. Spec: "Writing a theme".
// Pure (no file access) so it runs in the browser as well as the CLI: the
// caller passes in the base theme's CSS.
//
// The base theme is copied under the new name, then the config's values are
// laid over it. Every theme file has the same three kinds of rule, told apart
// by selector: light inputs, dark inputs, and light-mode system pins.

type Block = Map<string, string>
type Kind = "light" | "dark" | "pins"

function kindOf(selector: string): Kind {
  if (selector.includes(":not(")) return "pins"
  return selector.includes(".dark") ? "dark" : "light"
}

function parse(css: string): Record<Kind, Block> {
  const blocks: Record<Kind, Block> = {
    light: new Map(),
    dark: new Map(),
    pins: new Map(),
  }
  const body = css
    .replace(/\/\*[\s\S]*?\*\//g, "")
    .replace(/@import[^;]*;/g, "")
  for (const [, selector, decls] of body.matchAll(/([^{}]+)\{([^{}]*)\}/g)) {
    const block = blocks[kindOf(selector)]
    for (const decl of decls.split(";")) {
      const colon = decl.indexOf(":")
      if (colon === -1) continue
      block.set(decl.slice(0, colon).trim(), decl.slice(colon + 1).trim())
    }
  }
  return blocks
}

const rule = (selector: string, block: Block) =>
  `${selector} {\n${[...block].map(([k, v]) => `  ${k}: ${v};`).join("\n")}\n}\n`

/**
 * Builds the theme stylesheet for a parsed config.
 * @param baseCss the CSS of the theme named in `config.extends`
 */
export function generateThemeCss(config: GlazeConfig, baseCss: string): string {
  const { light, dark, pins } = parse(baseCss)
  const set = (
    block: Block,
    values: Record<string, string | undefined> | undefined
  ) => {
    for (const [k, v] of Object.entries(values ?? {}))
      if (v !== undefined) block.set(`--${k}`, v)
  }

  // Colour is per mode.
  set(light, config.color?.light)
  set(dark, config.color?.dark)

  // Everything else holds in both modes: set it on the light rule, and on the
  // dark rule too where the base theme gave it a dark value of its own.
  for (const group of [
    config.shape,
    config.space,
    config.type,
    config.elevation,
    config.motion,
    config.components,
  ]) {
    set(light, group)
    for (const [k, v] of Object.entries(group ?? {}))
      if (v !== undefined && dark.has(`--${k}`)) dark.set(`--${k}`, v)
  }

  // Pins reproduce the base palette's exact light neutrals. Once the light
  // palette changes they no longer match it, so derive instead.
  const keepPins =
    pins.size > 0 && Object.keys(config.color?.light ?? {}).length === 0

  // Fonts: importing the base theme's file loads its fonts, resolved from
  // inside Glaze (Nova's font comes with globals.css). Its rules are scoped
  // to its own name, so they don't touch this theme.
  const imports = [
    ...(config.extends === "nova"
      ? []
      : [`@amit-kap/glaze/themes/${config.extends}.css`]),
    ...(config.fonts ?? []),
  ]

  const t = `[data-theme="${config.name}"]`
  return [
    `/*\n * ${config.name}: generated by Glaze from a config, extending ${config.extends}.\n` +
      ` * Don't edit by hand: change the config and generate again.\n */\n`,
    // The config itself, so the file can be loaded back into the showcase.
    `/* glaze-config ${JSON.stringify(config).replaceAll("*/", "*\\/")} */\n`,
    imports.map((i) => `@import "${i}";`).join("\n") +
      (imports.length ? "\n" : ""),
    rule(t, light),
    rule(`${t}.dark,\n.dark ${t},\n${t} .dark`, dark),
    keepPins ? rule(`${t}:not(.dark, .dark *)`, pins) : "",
  ]
    .filter(Boolean)
    .join("\n")
}

/** Reads the config embedded in a generated theme file, if there is one. */
export function readEmbeddedConfig(css: string): unknown {
  const match = css.match(/\/\* glaze-config (\{[\s\S]*?\}) \*\//)
  return match ? JSON.parse(match[1]) : undefined
}
